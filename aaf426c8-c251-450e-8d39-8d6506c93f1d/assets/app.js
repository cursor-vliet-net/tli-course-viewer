    if (t.closest('#clearYes')) { S.edits = {}; S.removals = {}; S.comments = {}; save(); showFeedback(); toast('All feedback cleared'); return; }
    if (t.closest('.fb-undo')) { var li = t.closest('.fb-item'); deleteItem(li.getAttribute('data-store'), li.getAttribute('data-key')); showFeedback(); return; }
    if (!blk) return;
    if (t.closest('.ref')) {
      ev.preventDefault();
      var ref = blk.getAttribute('data-ref');
      $$('.blk.is-active').forEach(function (b) { if (b !== blk) b.classList.remove('is-active'); });
      blk.classList.toggle('is-active');
      if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(ref).catch(function () {});
      toast(ref);
      return;
    }
    if (MODE !== 'designer') return; /* teacher and student: links and quizzes only */
    if (t.closest('.ed-save')) return saveEdit();
    if (t.closest('.ed-cancel')) return cancelEdit();
    if (t.closest('.ed-reset') || t.closest('.st-reset')) return resetEdit(blk);
