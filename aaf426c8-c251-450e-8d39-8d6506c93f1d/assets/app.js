  function blockMD(el) {
    var tag = el.tagName.toLowerCase();
    if (/^h[1-6]$/.test(tag)) return new Array(+tag[1] + 1).join('#') + ' ' + inl(el).replace(/\n/g, ' ');
    if (tag === 'ul' || tag === 'ol') return listMD(el, 0);
    if (tag === 'table') return tableMD(el);
    if (tag === 'blockquote') return inl(el).split('\n').map(function (l) { return '> ' + l; }).join('\n');
    if (tag === 'pre') return '```\n' + el.textContent.replace(/\n$/, '') + '\n```';
    if (tag === 'figure') { var im = $('img', el); return '![' + (im.getAttribute('alt') || '') + '](' + im.getAttribute('data-src') + ')' + (el.getAttribute('data-marker') !== 'default' ? '{' + el.getAttribute('data-marker') + '}' : ''); }
    if (el.classList.contains('quiz')) return quizMD(el);
    return inl(el);
  }

  /* ---------------- sanitising stored HTML ---------------- */
  var ALLOWED = { P: 1, B: 1, STRONG: 1, I: 1, EM: 1, S: 1, DEL: 1, CODE: 1, A: 1, BR: 1, UL: 1, OL: 1, LI: 1, TABLE: 1, THEAD: 1, TBODY: 1, TR: 1, TH: 1, TD: 1, SPAN: 1, H1: 1, H2: 1, H3: 1, H4: 1, H5: 1, H6: 1, DIV: 1 };
  function sanitize(htmlStr) {
    var tpl = document.createElement('template'); tpl.innerHTML = htmlStr;
    (function walk(node) {
      Array.prototype.slice.call(node.childNodes).forEach(function (n) {
        if (n.nodeType === 8) { n.remove(); return; }
        if (n.nodeType !== 1) return;
        if (!ALLOWED[n.tagName]) {
          if (/^(SCRIPT|STYLE|IFRAME|OBJECT|EMBED)$/.test(n.tagName)) { n.remove(); return; }
          while (n.firstChild) n.parentNode.insertBefore(n.firstChild, n);
          n.remove(); return;
        }
        Array.prototype.slice.call(n.attributes).forEach(function (a) {
          var keep = (n.tagName === 'A' && (a.name === 'href' || a.name === 'data-href' || a.name === 'target' || a.name === 'rel' || a.name === 'data-internal')) ||
                     (a.name === 'class' && (n.tagName === 'TD' || n.tagName === 'TH' || n.tagName === 'SPAN' || n.tagName === 'I' || n.tagName === 'DIV')) ||
                     (n.tagName === 'DIV' && (a.name === 'data-scene' || a.name === 'role' || a.name === 'aria-label')) ||
                     (a.name === 'data-tag' || a.name === 'title' || a.name === 'aria-hidden') && n.tagName === 'SPAN' ||
                     (a.name === 'aria-hidden' && n.tagName === 'I');
          if (n.tagName === 'A' && a.name === 'href' && /^\s*javascript:/i.test(a.value)) keep = false;
          if (!keep) n.removeAttribute(a.name);
        });
        if (n.tagName === 'I' && !/\bfa-/.test(n.className)) { /* plain italic: fine */ }
        walk(n);
      });
    })(tpl.content);
    return tpl.innerHTML;
  }

