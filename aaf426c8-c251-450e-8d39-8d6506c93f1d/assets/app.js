  /* ---------------- HTML -> simple Markdown ---------------- */
  function inlineMD(node) {
    var out = '';
    Array.prototype.forEach.call(node.childNodes, function (n) {
      if (n.nodeType === 3) { out += n.nodeValue.replace(/\s+/g, ' '); return; }
      if (n.nodeType !== 1) return;
      var tag = n.tagName.toLowerCase(), inner;
      if (n.classList.contains('visually-hidden') || n.classList.contains('ref')) return;
      if (n.classList.contains('cell-tag')) { out += ' {' + n.getAttribute('data-tag') + '}'; return; }
      switch (tag) {
        case 'strong': case 'b': inner = inlineMD(n).trim(); out += inner ? '**' + inner + '**' : ''; break;
        case 'em': case 'i': if (n.classList.contains('fa-solid') || n.classList.contains('fa-regular')) break; inner = inlineMD(n).trim(); out += inner ? '*' + inner + '*' : ''; break;
        case 's': case 'del': inner = inlineMD(n).trim(); out += inner ? '~~' + inner + '~~' : ''; break;
        case 'code': out += '`' + n.textContent + '`'; break;
        case 'a': out += '[' + inlineMD(n).trim() + '](' + (n.getAttribute('data-href') || n.getAttribute('href') || '') + ')'; break;
        case 'br': out += '\n'; break;
        case 'img': out += '![' + (n.getAttribute('alt') || '') + '](' + (n.getAttribute('data-src') || n.getAttribute('src')) + ')'; break;
        case 'div': case 'p': inner = inlineMD(n).trim(); if (inner) out += (out && !/\n$/.test(out) ? '\n' : '') + inner; break;
        case 'ul': case 'ol': break; /* nested lists are handled by listMD */
        default: out += inlineMD(n);
      }
    });
    return out;
  }
  function inl(n) { return inlineMD(n).replace(/[ \t]+\n/g, '\n').replace(/\n[ \t]+/g, '\n').replace(/ {2,}/g, ' ').trim(); }
  function listMD(list, depth) {
    var lines = [], i = 1, ordered = list.tagName.toLowerCase() === 'ol';
    var indent = new Array(depth + 1).join('  ');
    Array.prototype.forEach.call(list.children, function (li) {
      if (li.tagName.toLowerCase() !== 'li') return;
      var text = inl(li);
      if (!text && !li.querySelector('ul,ol')) return;
      lines.push(indent + (ordered ? (i++) + '. ' : '- ') + text.replace(/\n/g, '\n' + indent + '  '));
      Array.prototype.forEach.call(li.children, function (c) {
        if (/^(ul|ol)$/i.test(c.tagName)) lines.push(listMD(c, depth + 1));
      });
    });
    return lines.join('\n');
  }
