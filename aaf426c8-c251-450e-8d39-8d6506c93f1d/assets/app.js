    if (t.closest('#dlJson')) { download('feedback-' + D.projectKey + '-' + fileStamp() + '.json', exportJSON(), 'application/json'); return; }
    if (t.closest('#clearAll')) { $('#clearConfirm').hidden = false; $('#clearYes').focus(); return; }
